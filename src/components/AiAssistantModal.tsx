import React, { useState } from 'react';
import {
  Sparkles,
  Send,
  Loader2,
  Check,
  Bell,
  Calendar,
  Droplets,
  Moon,
  Dumbbell,
  CheckSquare,
  AlertCircle,
  X,
  Plus,
} from 'lucide-react';
import confetti from 'canvas-confetti';
import { Habit, ExercisePlan, CalendarReminder, ReminderLeadTime } from '../types';
import {
  requestHabitAiSuggestions,
  AiHabitIntentResult,
  AiSuggestedHabit,
  AiSuggestedExercise,
  AiSuggestedReminder,
} from '../services/aiService';
import { formatFriendlyDate, getNext14Days, formatLeadTimeText } from '../utils/date';
import { playCheckChime } from '../utils/audio';

interface AiAssistantModalProps {
  isOpen: boolean;
  onClose: () => void;
  currentHabits: Habit[];
  onApplyAiSuggestions: (data: {
    habitsToAdd: Habit[];
    exercisesToAdd: ExercisePlan[];
    remindersToAdd: CalendarReminder[];
  }) => void;
  soundMuted: boolean;
  initialPrompt?: string;
}

const EXAMPLE_PROMPTS = [
  'Remind me to drink water daily',
  'Plan 3 morning runs next week and remind me 15m before each',
  'Set up a restful bedtime routine with wind-down reminders at 10:30 PM',
  'Remind me to do a 10-minute afternoon stretch at 3:00 PM',
  'Schedule a balanced 2-week workout plan with strength and cardio',
];

export const AiAssistantModal: React.FC<AiAssistantModalProps> = ({
  isOpen,
  onClose,
  currentHabits,
  onApplyAiSuggestions,
  soundMuted,
  initialPrompt = '',
}) => {
  const [prompt, setPrompt] = useState(initialPrompt);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<AiHabitIntentResult | null>(null);

  // Selection states for granular user control
  const [selectedHabits, setSelectedHabits] = useState<Record<number, boolean>>({});
  const [selectedExercises, setSelectedExercises] = useState<Record<number, boolean>>({});
  const [selectedReminders, setSelectedReminders] = useState<Record<number, boolean>>({});

  const next14Days = getNext14Days();
  const todayStr = next14Days[0];

  if (!isOpen) return null;

  const handleGenerate = async (customPrompt?: string) => {
    const textToSubmit = customPrompt || prompt;
    if (!textToSubmit.trim()) return;

    setLoading(true);
    setError(null);
    setResult(null);

    try {
      const data = await requestHabitAiSuggestions(textToSubmit.trim(), currentHabits, todayStr);
      setResult(data);

      // Default select all generated items
      const habitsMap: Record<number, boolean> = {};
      data.suggestedHabits.forEach((_, i) => (habitsMap[i] = true));
      setSelectedHabits(habitsMap);

      const exercisesMap: Record<number, boolean> = {};
      data.suggestedExercises.forEach((_, i) => (exercisesMap[i] = true));
      setSelectedExercises(exercisesMap);

      const remindersMap: Record<number, boolean> = {};
      data.suggestedReminders.forEach((_, i) => (remindersMap[i] = true));
      setSelectedReminders(remindersMap);
    } catch (err: unknown) {
      const e = err as Error;
      setError(e.message || 'Unable to generate suggestions. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  const handleApply = () => {
    if (!result) return;

    // Build habits
    const habitsToAdd: Habit[] = result.suggestedHabits
      .filter((_, idx) => selectedHabits[idx])
      .map((h, i) => ({
        id: `habit-ai-${Date.now()}-${i}`,
        name: h.name,
        category: h.category,
        targetValue: h.targetValue,
        unit: h.unit,
        color:
          h.category === 'water'
            ? '#0284c7'
            : h.category === 'sleep'
            ? '#6366f1'
            : h.category === 'exercise'
            ? '#059669'
            : '#8b5cf6',
        icon: h.icon || (h.category === 'water' ? 'droplets' : h.category === 'sleep' ? 'moon' : 'sparkles'),
        createdAt: new Date().toISOString(),
      }));

    // Build exercises
    const exercisesToAdd: ExercisePlan[] = result.suggestedExercises
      .filter((_, idx) => selectedExercises[idx])
      .map((e, i) => {
        const offset = Math.min(13, Math.max(0, e.dayOffset || 0));
        const targetDate = next14Days[offset] || todayStr;
        return {
          id: `plan-ai-${Date.now()}-${i}`,
          date: targetDate,
          title: e.title,
          type: e.type,
          targetDurationMin: e.targetDurationMin,
          plannedTime: e.plannedTime || '08:00',
          completed: false,
          intensity: e.intensity || 'moderate',
          notes: e.notes || 'Generated by HabitFlow AI',
        };
      });

    // Build reminders
    const remindersToAdd: CalendarReminder[] = result.suggestedReminders
      .filter((_, idx) => selectedReminders[idx])
      .map((r, i) => {
        const offset = Math.min(13, Math.max(0, r.dayOffset || 0));
        const targetDate = next14Days[offset] || todayStr;
        return {
          id: `rem-ai-${Date.now()}-${i}`,
          title: r.title,
          description: r.description || 'AI Suggested Reminder',
          date: targetDate,
          time: r.time || '12:00',
          category: r.category || 'habit',
          leadTimeMinutes: r.leadTimeMinutes ?? 15,
          status: 'pending',
          soundEnabled: true,
          createdAt: new Date().toISOString(),
        };
      });

    onApplyAiSuggestions({ habitsToAdd, exercisesToAdd, remindersToAdd });

    if (!soundMuted) {
      playCheckChime();
    }
    confetti({
      particleCount: 60,
      spread: 60,
      origin: { y: 0.6 },
    });

    onClose();
  };

  const totalSelected =
    Object.values(selectedHabits).filter(Boolean).length +
    Object.values(selectedExercises).filter(Boolean).length +
    Object.values(selectedReminders).filter(Boolean).length;

  return (
    <div className="fixed inset-0 z-50 bg-black/45 backdrop-blur-xs flex items-center justify-center p-3 sm:p-4 overflow-y-auto">
      <div className="bg-white rounded-3xl p-6 sm:p-8 max-w-2xl w-full shadow-2xl border border-slate-200 animate-in fade-in zoom-in-95 duration-150 my-auto max-h-[92vh] flex flex-col">
        
        {/* Header */}
        <div className="flex items-start justify-between gap-4 pb-4 border-b border-slate-100">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-linear-to-tr from-emerald-500 to-teal-600 flex items-center justify-center text-white shadow-xs">
              <Sparkles className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2 text-xs font-semibold text-emerald-700 uppercase tracking-wider">
                <span>Gemini 3.8 AI Assistant</span>
              </div>
              <h2 className="text-xl font-bold text-slate-900 mt-0.5">
                AI Habit &amp; Reminder Suggestions
              </h2>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-2 text-slate-400 hover:text-slate-600 rounded-xl hover:bg-slate-100 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Input Area */}
        <div className="mt-5 space-y-3">
          <label className="block text-xs font-semibold text-slate-700">
            Tell AI what you want to achieve or get reminded about:
          </label>
          <div className="relative">
            <input
              type="text"
              value={prompt}
              onChange={(e) => setPrompt(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter' && !loading) {
                  handleGenerate();
                }
              }}
              placeholder='e.g. "Remind me to drink water daily" or "Schedule 3 workouts next week"'
              className="w-full pl-4 pr-24 py-3 text-sm border border-slate-200 rounded-2xl focus:outline-none focus:ring-2 focus:ring-emerald-500 bg-slate-50 focus:bg-white shadow-2xs"
            />
            <button
              onClick={() => handleGenerate()}
              disabled={loading || !prompt.trim()}
              className="absolute right-1.5 top-1.5 bottom-1.5 px-4 bg-slate-900 hover:bg-slate-800 disabled:opacity-40 text-white rounded-xl text-xs font-semibold flex items-center gap-1.5 shadow-xs transition-colors"
            >
              {loading ? (
                <>
                  <Loader2 className="w-3.5 h-3.5 animate-spin" />
                  <span>Thinking...</span>
                </>
              ) : (
                <>
                  <Sparkles className="w-3.5 h-3.5 text-emerald-400" />
                  <span>Generate</span>
                </>
              )}
            </button>
          </div>

          {/* Quick Prompt Suggestions */}
          <div>
            <div className="text-[11px] font-semibold text-slate-400 mb-1.5">
              Quick prompt ideas:
            </div>
            <div className="flex flex-wrap gap-1.5">
              {EXAMPLE_PROMPTS.map((ex, idx) => (
                <button
                  key={idx}
                  type="button"
                  onClick={() => {
                    setPrompt(ex);
                    handleGenerate(ex);
                  }}
                  className="px-2.5 py-1 text-xs text-slate-600 bg-slate-100 hover:bg-slate-200 rounded-lg transition-colors text-left font-medium"
                >
                  {ex}
                </button>
              ))}
            </div>
          </div>
        </div>

        {/* Error message */}
        {error && (
          <div className="mt-4 p-3 bg-rose-50 border border-rose-200 rounded-xl flex items-start gap-2.5 text-xs text-rose-800">
            <AlertCircle className="w-4 h-4 shrink-0 mt-0.5 text-rose-600" />
            <div>
              <span className="font-semibold">Generation issue: </span>
              {error}
            </div>
          </div>
        )}

        {/* Results Container (Scrollable) */}
        {result && (
          <div className="mt-5 space-y-5 overflow-y-auto pr-1 flex-1 border-t border-slate-100 pt-4">
            {/* Summary & Motivational Banner */}
            <div className="bg-linear-to-r from-emerald-50/80 to-teal-50/60 border border-emerald-200/80 rounded-2xl p-4">
              <div className="flex items-center gap-2 text-xs font-bold text-emerald-800">
                <Sparkles className="w-4 h-4 text-emerald-600 shrink-0" />
                <span>{result.summary}</span>
              </div>
              <p className="text-xs text-slate-600 mt-1.5 leading-relaxed">
                {result.motivationalTip}
              </p>
            </div>

            {/* 1. Suggested Habits */}
            {result.suggestedHabits.length > 0 && (
              <div>
                <div className="flex items-center justify-between mb-2">
                  <h4 className="text-xs font-bold uppercase tracking-wider text-slate-500">
                    Suggested Daily Habits ({result.suggestedHabits.length})
                  </h4>
                  <span className="text-[11px] text-slate-400">Select to add to tracker</span>
                </div>
                <div className="space-y-2">
                  {result.suggestedHabits.map((habit, idx) => (
                    <label
                      key={idx}
                      className={`flex items-center justify-between p-3 rounded-xl border transition-all cursor-pointer ${
                        selectedHabits[idx]
                          ? 'bg-emerald-50/40 border-emerald-300'
                          : 'bg-white border-slate-200 opacity-60'
                      }`}
                    >
                      <div className="flex items-center gap-3">
                        <input
                          type="checkbox"
                          checked={!!selectedHabits[idx]}
                          onChange={(e) =>
                            setSelectedHabits({ ...selectedHabits, [idx]: e.target.checked })
                          }
                          className="rounded border-slate-300 text-emerald-600 focus:ring-emerald-500"
                        />
                        <div>
                          <span className="text-sm font-semibold text-slate-900">{habit.name}</span>
                          <span className="text-xs text-slate-500 ml-2">
                            ({habit.targetValue} {habit.unit})
                          </span>
                        </div>
                      </div>
                      <span className="text-[11px] font-semibold uppercase text-slate-500 bg-slate-100 px-2 py-0.5 rounded-md">
                        {habit.category}
                      </span>
                    </label>
                  ))}
                </div>
              </div>
            )}

            {/* 2. Suggested Reminders */}
            {result.suggestedReminders.length > 0 && (
              <div>
                <div className="flex items-center justify-between mb-2">
                  <h4 className="text-xs font-bold uppercase tracking-wider text-amber-700">
                    Suggested Timely Notifications &amp; Reminders ({result.suggestedReminders.length})
                  </h4>
                  <span className="text-[11px] text-slate-400">With self-chosen lead time</span>
                </div>
                <div className="space-y-2">
                  {result.suggestedReminders.map((rem, idx) => (
                    <label
                      key={idx}
                      className={`flex items-start justify-between p-3 rounded-xl border transition-all cursor-pointer ${
                        selectedReminders[idx]
                          ? 'bg-amber-50/40 border-amber-300'
                          : 'bg-white border-slate-200 opacity-60'
                      }`}
                    >
                      <div className="flex items-start gap-3">
                        <input
                          type="checkbox"
                          checked={!!selectedReminders[idx]}
                          onChange={(e) =>
                            setSelectedReminders({ ...selectedReminders, [idx]: e.target.checked })
                          }
                          className="rounded border-slate-300 text-amber-600 focus:ring-amber-500 mt-1"
                        />
                        <div>
                          <div className="text-sm font-semibold text-slate-900">{rem.title}</div>
                          {rem.description && (
                            <p className="text-xs text-slate-500 mt-0.5">{rem.description}</p>
                          )}
                          <div className="flex items-center gap-2 text-[11px] text-amber-800 font-medium mt-1">
                            <Bell className="w-3 h-3" />
                            <span>At {rem.time}</span>
                            <span>·</span>
                            <span>Alert {formatLeadTimeText(rem.leadTimeMinutes)}</span>
                          </div>
                        </div>
                      </div>
                      <span className="text-[11px] font-semibold text-amber-800 bg-amber-100 px-2 py-0.5 rounded-md shrink-0">
                        {rem.category}
                      </span>
                    </label>
                  ))}
                </div>
              </div>
            )}

            {/* 3. Suggested 2-Week Exercises */}
            {result.suggestedExercises.length > 0 && (
              <div>
                <div className="flex items-center justify-between mb-2">
                  <h4 className="text-xs font-bold uppercase tracking-wider text-sky-700">
                    Suggested Workouts for 2-Week Calendar ({result.suggestedExercises.length})
                  </h4>
                  <span className="text-[11px] text-slate-400">Added to 14-day schedule</span>
                </div>
                <div className="space-y-2">
                  {result.suggestedExercises.map((ex, idx) => {
                    const offset = Math.min(13, Math.max(0, ex.dayOffset || 0));
                    const workoutDate = next14Days[offset] || todayStr;

                    return (
                      <label
                        key={idx}
                        className={`flex items-center justify-between p-3 rounded-xl border transition-all cursor-pointer ${
                          selectedExercises[idx]
                            ? 'bg-sky-50/40 border-sky-300'
                            : 'bg-white border-slate-200 opacity-60'
                        }`}
                      >
                        <div className="flex items-center gap-3">
                          <input
                            type="checkbox"
                            checked={!!selectedExercises[idx]}
                            onChange={(e) =>
                              setSelectedExercises({ ...selectedExercises, [idx]: e.target.checked })
                            }
                            className="rounded border-slate-300 text-sky-600 focus:ring-sky-500"
                          />
                          <div>
                            <div className="text-sm font-semibold text-slate-900">{ex.title}</div>
                            <div className="text-xs text-slate-500 mt-0.5">
                              <span>{formatFriendlyDate(workoutDate)}</span>
                              <span> · </span>
                              <span>{ex.plannedTime} ({ex.targetDurationMin}m)</span>
                              <span> · </span>
                              <span className="capitalize">{ex.intensity || 'moderate'}</span>
                            </div>
                          </div>
                        </div>
                        <span className="text-[11px] font-semibold uppercase text-sky-800 bg-sky-100 px-2 py-0.5 rounded-md">
                          {ex.type}
                        </span>
                      </label>
                    );
                  })}
                </div>
              </div>
            )}
          </div>
        )}

        {/* Footer Actions */}
        <div className="mt-6 pt-4 border-t border-slate-100 flex items-center justify-between gap-3">
          <button
            type="button"
            onClick={onClose}
            className="px-4 py-2 text-xs font-medium text-slate-600 hover:bg-slate-100 rounded-xl transition-colors"
          >
            Cancel
          </button>

          {result && (
            <button
              type="button"
              onClick={handleApply}
              disabled={totalSelected === 0}
              className="px-5 py-2.5 text-xs sm:text-sm font-semibold text-white bg-slate-900 hover:bg-slate-800 disabled:opacity-40 rounded-xl shadow-xs transition-colors flex items-center gap-2"
            >
              <Check className="w-4 h-4 text-emerald-400" />
              <span>Add {totalSelected} Selected Items to App</span>
            </button>
          )}
        </div>

      </div>
    </div>
  );
};
